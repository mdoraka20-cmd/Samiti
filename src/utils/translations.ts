export type Language = 'bn' | 'en';

export const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function formatNumberWithLang(
  n: number | string | null | undefined,
  lang: Language = 'bn'
): string {
  if (n === null || n === undefined || n === '') return lang === 'bn' ? '০' : '0';
  const num = Number(n);
  if (isNaN(num)) return String(n);
  const formatted = num.toLocaleString('en-US');
  if (lang === 'en') return formatted;
  return formatted.replace(/[0-9]/g, (d) => BN_DIGITS[parseInt(d, 10)] || d);
}

export function formatCurrencyWithLang(
  amount: number | string | null | undefined,
  lang: Language = 'bn'
): string {
  const num = Number(amount) || 0;
  const numStr = formatNumberWithLang(num, lang);
  return lang === 'bn' ? `৳ ${numStr}` : `৳ ${numStr}`;
}

