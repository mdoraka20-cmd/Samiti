export function getMonthNameWithLang(monthStr: string, lang: Language = 'bn'): string {
  if (!monthStr) return '';
  const parts = monthStr.split('-');
  if (parts.length < 2) return monthStr;
  const year = parts[0];
  const monthIdx = parseInt(parts[1], 10) - 1;
  if (lang === 'en') {
    const monthName = EN_MONTH_NAMES[monthIdx] || '';
    return `${monthName} ${year}`;
  } else {
    const monthName = BN_MONTH_NAMES[monthIdx] || '';
    return `${monthName} ${formatNumberWithLang(year, 'bn')}`;
  }
}

export function formatDateWithLang(dateStr: string, lang: Language = 'bn'): string {
  if (!dateStr) return '';
  const [y, m, d] = dateStr.split('-');
  if (!d) return dateStr;
  if (lang === 'en') {
    return `${d}-${m}-${y}`;
  }
  return `${formatNumberWithLang(d, 'bn')}-${formatNumberWithLang(m, 'bn')}-${formatNumberWithLang(y, 'bn')}`;
}

// English Number to Words
export function numberToEnglishWords(num: number): string {
  if (!num || num === 0) return 'Zero Taka Only';
  const a = [
    '', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine',
    'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'
  ];
  const b = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];

  function inWords(n: number): string {
    if (n < 20) return a[n];
    if (n < 100) return b[Math.floor(n / 10)] + (n % 10 !== 0 ? ' ' + a[n % 10] : '');
    if (n < 1000) return a[Math.floor(n / 100)] + ' Hundred' + (n % 100 !== 0 ? ' ' + inWords(n % 100) : '');
    if (n < 100000) return inWords(Math.floor(n / 1000)) + ' Thousand' + (n % 1000 !== 0 ? ' ' + inWords(n % 1000) : '');
    if (n < 10000000) return inWords(Math.floor(n / 100000)) + ' Lakh' + (n % 100000 !== 0 ? ' ' + inWords(n % 100000) : '');
    return inWords(Math.floor(n / 10000000)) + ' Crore' + (n % 10000000 !== 0 ? ' ' + inWords(n % 10000000) : '');
  }

  return `${inWords(Math.floor(Math.abs(num)))} Taka Only`;
}

